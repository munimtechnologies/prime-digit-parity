# ------------------------------------------------- observable + null (verbatim from arc)
def digit_sum_parity(n, b):
    s = 0
    while n:
        s += n % b
        n //= b
    return s & 1


def lag_stats(pb):
    """From a 0/1 byte string pb, compute N_eff, s, and S^(k)=M-2*D_k for k in LAGS."""
    n_eff = len(pb)
    ones = pb.count(1)
    s = n_eff - 2 * ones
    out = {}
    for k in LAGS:
        if k >= n_eff:
            out[k] = None
            continue
        a = int.from_bytes(pb[: n_eff - k], "big")
        c = int.from_bytes(pb[k:], "big")
        d_k = (a ^ c).bit_count()
        m = n_eff - k
        out[k] = m - 2 * d_k
    return n_eff, s, out


def null_z(n_eff, s, S, k):
    """Exact marginal-preserving permutation-null mean, variance and z of S^(k)."""
    N_ = n_eff
    M = N_ - k
    n_shared = max(0, N_ - 2 * k)
    n_disjoint = M * (M - 1) // 2 - n_shared
    rho2 = Fraction(s * s - N_, N_ * (N_ - 1))
    rho4 = Fraction(
        s ** 4 - 6 * N_ * s * s + 8 * s * s + 3 * N_ * N_ - 6 * N_,
        N_ * (N_ - 1) * (N_ - 2) * (N_ - 3),
    )
    eS = M * rho2
    eS2 = M + 2 * n_shared * rho2 + 2 * n_disjoint * rho4
    var = eS2 - eS * eS
    varf = float(var)
    z = (S - float(eS)) / math.sqrt(varf) if varf > 0 else 0.0
    return float(eS), varf, z


# ------------------------------------------------- the multiplicative sieves (verbatim)
def collect_prime_gaps(N):
    sieve = bytearray(b"\x01") * (N + 1)
    sieve[0:2] = b"\x00\x00"
    for i in range(2, int(N ** 0.5) + 1):
        if sieve[i]:
            sieve[i * i::i] = b"\x00" * len(sieve[i * i::i])
    gaps = array("H")
    prev = None
    maxg = 0
    cnt = 0
    for n in range(2, N + 1):
        if sieve[n]:
            cnt += 1
            if prev is not None:
                g = n - prev
                if g > maxg:
                    maxg = g
                gaps.append(g)
            prev = n
    del sieve
    return gaps, cnt, maxg


def _small_primes(limit):
    sieve = bytearray(b"\x01") * (limit + 1)
    sieve[0:2] = b"\x00\x00"
    for i in range(2, int(limit ** 0.5) + 1):
        if sieve[i]:
            sieve[i * i::i] = b"\x00" * len(sieve[i * i::i])
    return [i for i in range(2, limit + 1) if sieve[i]]


def collect_squarefree_gaps(N):
    """Segmented mu^2 sieve: n is squarefree iff no p^2 divides n."""
    SEG = 1 << 22
    root = int(N ** 0.5)
    primes = _small_primes(root)
    psq = [p * p for p in primes if p * p <= N]
    gaps = array("H")
    cnt = 0
    prev = None
    maxg = 0
    lo = 1
    while lo <= N:
        hi = min(lo + SEG, N + 1)
        length = hi - lo
        seg = bytearray(b"\x01") * length
        for p2 in psq:
            if p2 > hi - 1:
                break
            start = ((lo + p2 - 1) // p2) * p2
            for m in range(start, hi, p2):
                seg[m - lo] = 0
        for off in range(length):
            if seg[off]:
                q = lo + off
                cnt += 1
                if prev is not None:
                    g = q - prev
                    if g > maxg:
                        maxg = g
                    gaps.append(g)
                prev = q
        lo = hi
    return gaps, cnt, maxg


def build_bad(limit):
    """bad[n] == 1 iff n is NOT a sum of two squares.
    n in S iff every prime p = 3 (mod 4) divides n to an even power."""
    root = int(limit ** 0.5)
    sieve = bytearray(b"\x01") * (limit + 1)
    sieve[0:2] = b"\x00\x00"
    for i in range(2, root + 1):
        if sieve[i]:
            sieve[i * i::i] = b"\x00" * len(sieve[i * i::i])
    bad = bytearray(limit + 1)
    scratch = bytearray(limit + 1)
    for p in range(3, limit + 1):
        if not sieve[p] or p % 4 != 3:
            continue
        if p > root:
            bad[p::p] = b"\x01" * (limit // p)
        else:
            pk = p
            while pk <= limit:
                for n in range(pk, limit + 1, pk):
                    scratch[n] ^= 1
                pk *= p
            for n in range(p, limit + 1, p):
                if scratch[n]:
                    bad[n] = 1
                    scratch[n] = 0
    del sieve, scratch
    return bad


def collect_sumsq_gaps(N):
    bad = build_bad(N)
    gaps = array("H")
    cnt = 0
    prev = None
    maxg = 0
    for n in range(1, N + 1):
        if bad[n] == 0:
            cnt += 1
            if prev is not None:
                g = n - prev
                if g > maxg:
                    maxg = g
                gaps.append(g)
            prev = n
    del bad
    return gaps, cnt, maxg


